-- Modelo SaaS multi-tenant: cada organización (liga, club, empresa) tiene sus propios
-- torneos, sedes, canchas, equipos y miembros. Hasta ahora solo había datos de demostración,
-- así que el esquema anterior se reemplaza por completo.

DROP TABLE IF EXISTS fixture_event CASCADE;
DROP TABLE IF EXISTS fixture_set CASCADE;
DROP TABLE IF EXISTS fixture CASCADE;
DROP TABLE IF EXISTS player CASCADE;
DROP TABLE IF EXISTS team CASCADE;
DROP TABLE IF EXISTS tournament CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE organization (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(60)  NOT NULL UNIQUE,
    name        VARCHAR(80)  NOT NULL,
    short_name  VARCHAR(3)   NOT NULL,
    color       VARCHAR(7)   NOT NULL,
    city        VARCHAR(80),
    description VARCHAR(300),
    plan        VARCHAR(10)  NOT NULL,
    demo        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE membership (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT      NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    user_id         BIGINT REFERENCES app_user (id) ON DELETE CASCADE,
    email           VARCHAR(120) NOT NULL,
    role            VARCHAR(12)  NOT NULL,
    status          VARCHAR(10)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_membership UNIQUE (organization_id, email)
);

CREATE INDEX idx_membership_user ON membership (user_id);

CREATE TABLE venue (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT       NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    name            VARCHAR(80)  NOT NULL,
    address         VARCHAR(160)
);

CREATE INDEX idx_venue_org ON venue (organization_id);

CREATE TABLE court (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT      NOT NULL REFERENCES venue (id) ON DELETE CASCADE,
    name     VARCHAR(60) NOT NULL,
    surface  VARCHAR(60),
    sports   VARCHAR(160),
    position INTEGER     NOT NULL DEFAULT 0
);

CREATE INDEX idx_court_venue ON court (venue_id);

-- Horario en que cada cancha se puede usar (día de la semana 1 = lunes … 7 = domingo)
CREATE TABLE court_availability (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id    BIGINT  NOT NULL REFERENCES court (id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL,
    start_time  TIME    NOT NULL,
    end_time    TIME    NOT NULL
);

CREATE INDEX idx_availability_court ON court_availability (court_id);

-- Bloqueos puntuales: mantenimiento, eventos, lluvia
CREATE TABLE court_block (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id  BIGINT       NOT NULL REFERENCES court (id) ON DELETE CASCADE,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    reason    VARCHAR(120)
);

CREATE INDEX idx_block_court ON court_block (court_id);

CREATE TABLE tournament (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id   BIGINT       NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
    slug              VARCHAR(90)  NOT NULL,
    name              VARCHAR(80)  NOT NULL,
    category          VARCHAR(40),
    sport             VARCHAR(20)  NOT NULL,
    format            VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    description       VARCHAR(400),
    start_date        DATE,
    double_round      BOOLEAN      NOT NULL DEFAULT FALSE,
    groups_count      INTEGER      NOT NULL DEFAULT 0,
    advance_per_group INTEGER      NOT NULL DEFAULT 0,
    third_place       BOOLEAN      NOT NULL DEFAULT FALSE,
    block_minutes     INTEGER      NOT NULL,
    min_rest_hours    INTEGER      NOT NULL DEFAULT 0,
    days_between      INTEGER      NOT NULL DEFAULT 7,
    champion_team_id  BIGINT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_tournament_slug UNIQUE (organization_id, slug)
);

CREATE INDEX idx_tournament_org ON tournament (organization_id);

CREATE TABLE tournament_court (
    tournament_id BIGINT NOT NULL REFERENCES tournament (id) ON DELETE CASCADE,
    court_id      BIGINT NOT NULL REFERENCES court (id) ON DELETE CASCADE,
    PRIMARY KEY (tournament_id, court_id)
);

CREATE TABLE team (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT      NOT NULL REFERENCES tournament (id) ON DELETE CASCADE,
    name          VARCHAR(60) NOT NULL,
    short_name    VARCHAR(4)  NOT NULL,
    color         VARCHAR(7)  NOT NULL,
    group_label   VARCHAR(2),
    seed          INTEGER     NOT NULL
);

CREATE INDEX idx_team_tournament ON team (tournament_id);

CREATE TABLE player (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id      BIGINT      NOT NULL REFERENCES team (id) ON DELETE CASCADE,
    name         VARCHAR(60) NOT NULL,
    shirt_number INTEGER,
    document     VARCHAR(30)
);

CREATE INDEX idx_player_team ON player (team_id);

CREATE TABLE fixture (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id     BIGINT      NOT NULL REFERENCES tournament (id) ON DELETE CASCADE,
    stage             VARCHAR(12) NOT NULL,
    round_number      INTEGER     NOT NULL,
    group_label       VARCHAR(2),
    bracket_position  INTEGER,
    home_team_id      BIGINT REFERENCES team (id) ON DELETE SET NULL,
    away_team_id      BIGINT REFERENCES team (id) ON DELETE SET NULL,
    court_id          BIGINT REFERENCES court (id) ON DELETE SET NULL,
    referee_id        BIGINT REFERENCES app_user (id) ON DELETE SET NULL,
    scheduled_at      TIMESTAMP WITH TIME ZONE,
    status            VARCHAR(12) NOT NULL,
    cancel_reason     VARCHAR(120),
    period_number     INTEGER     NOT NULL DEFAULT 0,
    period_started_at TIMESTAMP WITH TIME ZONE,
    clock_speed       DOUBLE PRECISION NOT NULL DEFAULT 1,
    home_score        INTEGER     NOT NULL DEFAULT 0,
    away_score        INTEGER     NOT NULL DEFAULT 0,
    home_penalties    INTEGER,
    away_penalties    INTEGER,
    winner_team_id    BIGINT,
    bye               BOOLEAN     NOT NULL DEFAULT FALSE,
    started_at        TIMESTAMP WITH TIME ZONE,
    finished_at       TIMESTAMP WITH TIME ZONE,
    version           BIGINT      NOT NULL DEFAULT 0
);

CREATE INDEX idx_fixture_tournament ON fixture (tournament_id);
CREATE INDEX idx_fixture_court_time ON fixture (court_id, scheduled_at);
CREATE INDEX idx_fixture_referee ON fixture (referee_id);

CREATE TABLE fixture_set (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id BIGINT  NOT NULL REFERENCES fixture (id) ON DELETE CASCADE,
    set_index  INTEGER NOT NULL,
    home       INTEGER NOT NULL DEFAULT 0,
    away       INTEGER NOT NULL DEFAULT 0,
    finished   BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_fixture_set_fixture ON fixture_set (fixture_id);

CREATE TABLE fixture_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fixture_id    BIGINT      NOT NULL REFERENCES fixture (id) ON DELETE CASCADE,
    event_type    VARCHAR(16) NOT NULL,
    team_id       BIGINT      NOT NULL REFERENCES team (id) ON DELETE CASCADE,
    player_id     BIGINT REFERENCES player (id) ON DELETE SET NULL,
    period_number INTEGER     NOT NULL,
    game_minute   INTEGER,
    set_index     INTEGER,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_fixture_event_fixture ON fixture_event (fixture_id);
